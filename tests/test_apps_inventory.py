def test_start_menu_win32_app_resolves_known_folder_exe(records):
    notepad = records["notepad"]
    assert notepad.exe == "C:\\Windows\\system32\\notepad.exe"
    assert notepad.process_names == ["notepad.exe"]
    assert notepad.sources == ["startmenu"]


def test_appx_package_supplies_version_publisher_process_and_schemes(records):
    calc = records["calculator"]
    assert calc.aumid == "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"
    assert calc.package_family == "Microsoft.WindowsCalculator_8wekyb3d8bbwe"
    assert calc.version == "11.2607.0.0"
    assert calc.publisher == "Microsoft Corporation"
    assert calc.process_names == ["calculatorapp.exe"]
    assert calc.uri_schemes == ["calculator", "ms-calculator"]
    assert "rechner" in calc.aliases
    assert set(calc.sources) == {"startmenu", "appx"}


