def _manifest(location):
    if location and location.endswith("Calc"):
        return {
            "applications": [{"id": "App", "executable": "CalculatorApp.exe"}],
            "protocols": ["calculator", "ms-calculator"],
        }
    return {"applications": [], "protocols": []}


def _resolver(app_id):
    return app_id.replace("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}", "C:\\Windows\\system32")


