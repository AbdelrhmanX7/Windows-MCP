"""Installed-app inventory: merge the raw sources and cache the result."""

from __future__ import annotations

import json
import logging
import os
import threading
import time
from collections.abc import Callable
from pathlib import Path

from windows_mcp.apps import sources
from windows_mcp.apps.models import AppRecord, normalize_name, slugify

logger = logging.getLogger(__name__)

DEFAULT_TTL_SEC = 6 * 60 * 60
CACHE_FILE_NAME = "apps-inventory.json"
CACHE_VERSION = 1

# Classic AUMIDs whose process cannot be derived from the AppID itself.
_WELL_KNOWN_AUMIDS = {
    "microsoft.windows.explorer": ("explorer.exe", ["file explorer", "explorer"]),
    "msedge": ("msedge.exe", ["edge"]),
    "chrome": ("chrome.exe", ["chrome"]),
    "microsoft.windows.shell.rundialog": (None, ["run"]),
}
# Start-menu names whose AUMID carries no executable (AutoGenerated / shell AUMIDs).
_WELL_KNOWN_NAMES = {
    "task manager": "taskmgr.exe",
    "windows media player": "wmplayer.exe",
    "remote desktop connection": "mstsc.exe",
    "control panel": "control.exe",
    "internet explorer": "iexplore.exe",
}
# URI schemes the OS registers without tying them to the owning app's manifest.
_WELL_KNOWN_SCHEMES = {
    "ms-settings": "windows.immersivecontrolpanel_",
    "ms-screenclip": "microsoft.screensketch_",
}
_SKIP_UNINSTALL_RELEASES = {"update", "hotfix", "security update", "service pack"}
_DOC_SUFFIXES = (".url", ".txt", ".chm", ".htm", ".html", ".pdf", ".rtf")


def _publisher_from_dn(publisher: str | None) -> str | None:
    """Return the CN of an AppX publisher DN (``CN=Spotify AB, O=...``)."""
    if not publisher:
        return None
    for part in publisher.split(","):
        part = part.strip()
        if part.upper().startswith("CN="):
            return part[3:].strip('"')
    return publisher


def _strip_vendor(normalized: str) -> str:
    for prefix in ("microsoft ", "google ", "mozilla ", "adobe "):
        if normalized.startswith(prefix):
            return normalized[len(prefix) :]
    return normalized


def _is_noise_start_entry(name: str, app_id: str) -> bool:
    lowered_name = name.lower()
    lowered_id = app_id.lower()
    if lowered_name.startswith(("uninstall", "readme", "help ", "license")):
        return True
    if lowered_id.startswith(("http://", "https://")):
        return True
    return lowered_id.endswith(_DOC_SUFFIXES)


def merge_sources(
    shell: dict[str, list[dict]],
    uninstall: list[dict],
    protocols: list[dict],
    *,
    manifest_reader: Callable[[str | None], dict] = sources.read_appx_manifest,
    known_folder_resolver: Callable[[str], str | None] = sources.resolve_known_folder_path,
) -> list[AppRecord]:
    """Normalize every source into one :class:`AppRecord` per app.

    Args:
        shell: ``{startapps, appsfolder, appx}`` rows from the PowerShell query.
        uninstall: Win32 uninstall registry entries.
        protocols: URL protocol handlers (``scheme``, ``exe``).
        manifest_reader: Reads an AppX manifest given its install location.
        known_folder_resolver: Resolves ``{GUID}\\rel\\app.exe`` AppIDs to paths.

    Returns:
        Records sorted by name.
    """
    by_aumid: dict[str, AppRecord] = {}
    records: list[AppRecord] = []

    # 1. Start-menu entries (Get-StartApps first, AppsFolder adds localized names).
    for source_key in ("startapps", "appsfolder"):
        for row in shell.get(source_key, []):
            name = (row.get("Name") or "").strip()
            app_id = (row.get("AppID") or "").strip()
            if not name or not app_id or _is_noise_start_entry(name, app_id):
                continue
            existing = by_aumid.get(app_id.lower())
            if existing is not None:
                existing.add_alias(name)
                continue
            record = AppRecord(name=name, aumid=app_id)
            record.add_source("startmenu")
            if "!" in app_id:
                record.package_family = app_id.split("!", 1)[0]
            else:
                exe = known_folder_resolver(app_id) if app_id.lower().endswith(".exe") else None
                if exe:
                    record.exe = exe
                    record.add_process(Path(exe.replace("\\", "/")).name)
                record.add_process(_WELL_KNOWN_NAMES.get(name.lower()))
                well_known = _WELL_KNOWN_AUMIDS.get(app_id.lower())
                if well_known:
                    record.add_process(well_known[0])
                    for alias in well_known[1]:
                        record.add_alias(alias)
            by_aumid[app_id.lower()] = record
            records.append(record)

    # 2. AppX packages: version, publisher, executable and declared protocols.
    by_family: dict[str, list[AppRecord]] = {}
    for record in records:
        if record.package_family:
            by_family.setdefault(record.package_family.lower(), []).append(record)
    for package in shell.get("appx", []):
        family = (package.get("PackageFamilyName") or "").lower()
        matched = by_family.get(family)
        if not matched:
            continue
        manifest = manifest_reader(package.get("InstallLocation"))
        executables = {
            (app.get("id") or "").lower(): app.get("executable")
            for app in manifest.get("applications", [])
        }
        for record in matched:
            record.add_source("appx")
            record.version = record.version or package.get("Version")
            record.publisher = record.publisher or _publisher_from_dn(package.get("Publisher"))
            record.install_location = record.install_location or package.get("InstallLocation")
            app_id = record.aumid.split("!", 1)[1].lower() if record.aumid else ""
            executable = executables.get(app_id)
            if executable:
                record.add_process(Path(executable.replace("\\", "/")).name)
                if not record.exe and record.install_location:
                    record.exe = str(Path(record.install_location) / executable)
            for scheme in manifest.get("protocols", []):
                record.add_scheme(scheme)
            if package.get("Name"):
                record.add_alias(package["Name"].split(".")[-1])

    # 3. Win32 uninstall entries: join by exe path, install dir, then name.
    def find_win32(entry_exe: str | None, location: str | None, name: str) -> AppRecord | None:
        if entry_exe:
            for record in records:
                if record.exe and record.exe.lower() == entry_exe.lower():
                    return record
        if location:
            prefix = location.lower().rstrip("\\") + "\\"
            for record in records:
                if record.exe and record.exe.lower().startswith(prefix):
                    return record
        normalized = _strip_vendor(normalize_name(name))
        for record in records:
            if _strip_vendor(normalize_name(record.name)) == normalized:
                return record
        return None

    for entry in uninstall:
        name = (entry.get("DisplayName") or "").strip()
        if not name or entry.get("SystemComponent") == 1 or entry.get("ParentKeyName"):
            continue
        if "(kb" in name.lower():
            continue
        if str(entry.get("ReleaseType") or "").lower() in _SKIP_UNINSTALL_RELEASES:
            continue
        icon_exe = sources.exe_from_command(entry.get("DisplayIcon"))
        if icon_exe and "unins" in Path(icon_exe.replace("\\", "/")).name.lower():
            icon_exe = None
        location = (entry.get("InstallLocation") or "").strip().strip('"') or None
        record = find_win32(icon_exe, location, name)
        if record is None:
            record = AppRecord(name=name)
            records.append(record)
        else:
            record.add_alias(name)
        record.add_source("uninstall")
        record.publisher = record.publisher or entry.get("Publisher")
        record.version = record.version or entry.get("DisplayVersion")
        record.install_location = record.install_location or location
        if icon_exe and not record.exe:
            record.exe = icon_exe
        if icon_exe:
            record.add_process(Path(icon_exe.replace("\\", "/")).name)

    # 4. URL protocol handlers, mapped through the handler's executable.
    by_exe: dict[str, AppRecord] = {}
    by_process: dict[str, AppRecord] = {}
    for record in records:
        if record.exe:
            by_exe.setdefault(record.exe.lower(), record)
        for process in record.process_names:
            by_process.setdefault(process, record)
    for protocol in protocols:
        exe = protocol.get("exe")
        if not exe:
            continue
        record = by_exe.get(exe.lower()) or by_process.get(
            Path(exe.replace("\\", "/")).name.lower()
        )
        if record is not None:
            record.add_scheme(protocol.get("scheme"))
            record.add_source("protocol")

    known_schemes = {p.get("scheme") for p in protocols}
    for scheme, family_prefix in _WELL_KNOWN_SCHEMES.items():
        if scheme not in known_schemes:
            continue
        for record in records:
            if (record.package_family or "").lower().startswith(family_prefix):
                record.add_scheme(scheme)

    # 5. Collapse duplicates that share an id (same display name from two sources).
    merged: dict[str, AppRecord] = {}
    for record in records:
        key = record.id
        if not key:
            continue
        if key in merged:
            _absorb(merged[key], record)
        else:
            merged[key] = record
    for record in merged.values():
        record.finalize()
    return sorted(merged.values(), key=lambda r: r.name.lower())


def _absorb(target: AppRecord, other: AppRecord) -> None:
    for attr in ("aumid", "exe", "publisher", "version", "install_location", "package_family"):
        if not getattr(target, attr) and getattr(other, attr):
            setattr(target, attr, getattr(other, attr))
    for alias in other.aliases:
        target.add_alias(alias)
    for process in other.process_names:
        target.add_process(process)
    for scheme in other.uri_schemes:
        target.add_scheme(scheme)
    for source in other.sources:
        target.add_source(source)


def gather_inventory() -> tuple[list[AppRecord], dict[str, str | None]]:
    """Read every source on this machine and merge them.

    Returns:
        ``(records, protocols)`` where *protocols* maps every registered URL
        scheme to its handler executable (``None`` for packaged handlers).
    """
    started = time.perf_counter()
    shell = sources.read_shell_sources()
    t_shell = time.perf_counter()
    try:
        uninstall = sources.read_uninstall_entries()
    except Exception:
        logger.warning("Reading uninstall keys failed", exc_info=True)
        uninstall = []
    try:
        protocols = sources.read_url_protocols()
    except Exception:
        logger.warning("Reading URL protocols failed", exc_info=True)
        protocols = []
    t_registry = time.perf_counter()
    records = merge_sources(shell, uninstall, protocols)
    logger.info(
        "App inventory: %d apps (powershell %.0f ms, registry %.0f ms, merge %.0f ms)",
        len(records),
        (t_shell - started) * 1000,
        (t_registry - t_shell) * 1000,
        (time.perf_counter() - t_registry) * 1000,
    )
    return records, {p["scheme"]: p.get("exe") for p in protocols}


def default_cache_dir() -> Path:
    from platformdirs import user_cache_dir

    return Path(user_cache_dir("windows-mcp", appauthor=False))


def _ttl_from_env() -> float:
    value = os.getenv("WINDOWS_MCP_APPS_TTL", "")
    try:
        return float(value) if value.strip() else DEFAULT_TTL_SEC
    except ValueError:
        logger.warning("Invalid WINDOWS_MCP_APPS_TTL %r, using default", value)
        return DEFAULT_TTL_SEC


class AppInventory:
    """In-memory + on-disk cache of the installed-app inventory.

    Args:
        gather: Callable returning ``(records, protocols)``; defaults to the real
            Windows readers.
        cache_dir: Directory holding the JSON cache; ``None`` disables disk caching.
        ttl: Seconds before a cached inventory is considered stale.
        clock: Time source (``time.time``), injectable for tests.
    """

    def __init__(
        self,
        gather: Callable[[], tuple[list[AppRecord], dict]] = gather_inventory,
        cache_dir: Path | None | bool = True,
        ttl: float | None = None,
        clock: Callable[[], float] = time.time,
    ) -> None:
        self._gather = gather
        self._cache_dir = default_cache_dir() if cache_dir is True else (cache_dir or None)
        self.ttl = _ttl_from_env() if ttl is None else ttl
        self._clock = clock
        self._lock = threading.Lock()
        self._records: list[AppRecord] | None = None
        self._protocols: dict[str, str | None] = {}
        self._created: float = 0.0

    @property
    def cache_path(self) -> Path | None:
        return self._cache_dir / CACHE_FILE_NAME if self._cache_dir else None

    @property
    def created(self) -> float:
        return self._created

    def _fresh(self, created: float) -> bool:
        return self._clock() - created < self.ttl

    def apps(self, refresh: bool = False) -> list[AppRecord]:
        """Return the inventory, gathering it when missing, stale or *refresh* is set."""
        with self._lock:
            if not refresh:
                if self._records is not None and self._fresh(self._created):
                    return self._records
                if self._load_disk():
                    return self._records
            records, protocols = self._gather()
            self._records, self._protocols, self._created = records, protocols, self._clock()
            self._save_disk()
            return self._records

    def protocols(self) -> dict[str, str | None]:
        self.apps()
        return self._protocols

    def _load_disk(self) -> bool:
        path = self.cache_path
        if path is None or not path.is_file():
            return False
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if data.get("version") != CACHE_VERSION or not self._fresh(float(data["created"])):
                return False
            self._records = [AppRecord.from_dict(item) for item in data["apps"]]
            self._protocols = dict(data.get("protocols") or {})
            self._created = float(data["created"])
            return True
        except Exception:
            logger.warning("Ignoring unreadable app inventory cache %s", path, exc_info=True)
            return False

    def _save_disk(self) -> None:
        path = self.cache_path
        if path is None:
            return
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            payload = {
                "version": CACHE_VERSION,
                "created": self._created,
                "apps": [record.to_dict() for record in self._records or []],
                "protocols": self._protocols,
            }
            tmp = path.with_suffix(".tmp")
            tmp.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
            os.replace(tmp, path)
        except OSError:
            logger.warning("Could not write app inventory cache %s", path, exc_info=True)

    # -- lookups -------------------------------------------------------------

    def find(self, query: str) -> AppRecord | None:
        """Resolve *query* (id, name, alias, process or AUMID) to one app."""
        matches = self.search(query, limit=1)
        return matches[0] if matches else None

    def search(self, query: str | None, limit: int | None = None) -> list[AppRecord]:
        """Filter apps by *query*: exact, then substring, then fuzzy matches."""
        records = self.apps()
        if not query or not query.strip():
            return records[:limit] if limit else list(records)
        q = query.strip().lower()
        q_slug = slugify(q)
        exact, partial = [], []
        for record in records:
            names = record.all_names()
            keys = {record.id, *(n for n in names), *record.process_names}
            if record.aumid:
                keys.add(record.aumid.lower())
            if q in keys or q_slug == record.id or q + ".exe" in record.process_names:
                exact.append(record)
            elif any(q in n for n in names):
                partial.append(record)
        results = exact + sorted(partial, key=lambda r: len(r.name))
        if not results:
            results = self._fuzzy(q, records)
        return results[:limit] if limit else results

    @staticmethod
    def _fuzzy(q: str, records: list[AppRecord]) -> list[AppRecord]:
        from thefuzz import fuzz

        scored = []
        for record in records:
            score = max(fuzz.WRatio(q, name) for name in record.all_names())
            if score >= 75:
                scored.append((score, record))
        scored.sort(key=lambda item: (-item[0], item[1].name.lower()))
        return [record for _, record in scored]

    def for_process(self, process_name: str) -> AppRecord | None:
        """Return the app owning *process_name* (``chrome.exe``) from the cached inventory."""
        if self._records is None:
            return None
        process_name = process_name.lower()
        for record in self._records:
            if process_name in record.process_names:
                return record
        return None


_default_inventory: AppInventory | None = None
_default_lock = threading.Lock()


def get_inventory() -> AppInventory:
    """Return the process-wide inventory singleton."""
    global _default_inventory
    with _default_lock:
        if _default_inventory is None:
            _default_inventory = AppInventory()
        return _default_inventory
